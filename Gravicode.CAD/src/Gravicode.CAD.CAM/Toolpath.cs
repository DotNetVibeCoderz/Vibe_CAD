using System.Globalization;
using System.Text;

namespace Gravicode.CAD.CAM;

public enum ToolType { FlatEndMill, BallEndMill, Drill, Extruder }

public sealed record Tool(string Name, double Diameter, ToolType Type = ToolType.FlatEndMill, double FeedRate = 800, double PlungeRate = 300, int SpindleRpm = 12000)
{
    public double Radius => Diameter / 2;
    public static Tool EndMill(double d) => new($"Ø{d} flat end mill", d);
    public static Tool Drill(double d) => new($"Ø{d} drill", d, ToolType.Drill, 200, 120, 4000);
}

public enum MoveKind { Rapid, Linear }

/// <summary>Single machine move. For additive paths <see cref="Extrude"/> is the filament length (mm) for this move.</summary>
public readonly record struct Move(MoveKind Kind, Vec3 To, double Feed, double Extrude = 0);

/// <summary>Ordered list of moves for one tool.</summary>
public sealed class Toolpath(string name, Tool tool)
{
    public string Name { get; } = name;
    public Tool Tool { get; } = tool;
    public List<Move> Moves { get; } = [];
    public double SafeZ { get; set; } = 5;

    public void Rapid(Vec3 p) => Moves.Add(new(MoveKind.Rapid, p, 0));
    public void Feed(Vec3 p, double feed, double extrude = 0) => Moves.Add(new(MoveKind.Linear, p, feed, extrude));

    public (double CutLength, double RapidLength, TimeSpan Time) Estimate(double rapidRate = 3000, Vec3? start = null)
    {
        double cut = 0, rapid = 0, minutes = 0;
        var cur = start ?? new Vec3(0, 0, SafeZ);
        foreach (var m in Moves)
        {
            double l = Vec3.Distance(cur, m.To);
            if (m.Kind == MoveKind.Rapid) { rapid += l; minutes += l / rapidRate; }
            else { cut += l; minutes += l / Math.Max(m.Feed, 1); }
            cur = m.To;
        }
        return (cut, rapid, TimeSpan.FromMinutes(minutes));
    }

    /// <summary>Preview polylines (cut moves orange, rapids grey) for display in any viewer.</summary>
    public IEnumerable<Polyline3> ToPolylines(Vec3? start = null)
    {
        var cur = start ?? new Vec3(0, 0, SafeZ);
        List<Vec3>? run = null; MoveKind kind = MoveKind.Rapid;
        foreach (var m in Moves)
        {
            if (run == null || m.Kind != kind)
            {
                if (run is { Count: > 1 }) yield return new Polyline3(run) { Layer = kind == MoveKind.Rapid ? "RAPID" : "CUT", Color = kind == MoveKind.Rapid ? CadColor.FromHex("#8A94A3") : CadColor.Orange };
                run = [cur]; kind = m.Kind;
            }
            run.Add(m.To); cur = m.To;
        }
        if (run is { Count: > 1 }) yield return new Polyline3(run) { Layer = kind == MoveKind.Rapid ? "RAPID" : "CUT", Color = kind == MoveKind.Rapid ? CadColor.FromHex("#8A94A3") : CadColor.Orange };
    }
}

public enum GCodeFlavor { Grbl, Marlin, LinuxCnc }

/// <summary>Post-processor producing G-code text from toolpaths.</summary>
public static class GCodeWriter
{
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;
    private static string N(double v) => v.ToString("0.###", Inv);

    public static string Write(IEnumerable<Toolpath> paths, GCodeFlavor flavor = GCodeFlavor.Grbl, string? programName = null, PrintSettings? print = null)
    {
        var sb = new StringBuilder();
        var list = paths.ToList();
        bool additive = list.Any(p => p.Tool.Type == ToolType.Extruder);
        sb.AppendLine($"; {programName ?? "Gravicode.CAD program"}");
        sb.AppendLine($"; Generated by {GravicodeCad.ProductName} {GravicodeCad.Version} - {GravicodeCad.Credits}");
        foreach (var p in list)
        {
            var (cut, rapid, time) = p.Estimate();
            sb.AppendLine($"; {p.Name}: tool {p.Tool.Name}, cut {N(cut)} mm, rapid {N(rapid)} mm, est. {time:hh\\:mm\\:ss}");
        }
        sb.AppendLine("G21 ; mm");
        sb.AppendLine("G90 ; absolute");
        if (additive)
        {
            var s = print ?? new PrintSettings();
            sb.AppendLine($"M140 S{N(s.BedTemperature)}");
            sb.AppendLine($"M104 S{N(s.NozzleTemperature)}");
            sb.AppendLine($"M190 S{N(s.BedTemperature)}");
            sb.AppendLine($"M109 S{N(s.NozzleTemperature)}");
            sb.AppendLine("G28 ; home");
            sb.AppendLine("M83 ; relative extrusion");
            sb.AppendLine("G92 E0");
        }
        else if (flavor != GCodeFlavor.Marlin) sb.AppendLine("G17 G94 G54");

        double lastF = -1;
        foreach (var p in list)
        {
            sb.AppendLine($"; --- {p.Name} ---");
            if (!additive)
            {
                if (flavor == GCodeFlavor.LinuxCnc) sb.AppendLine("T1 M6");
                sb.AppendLine($"M3 S{p.Tool.SpindleRpm}");
                sb.AppendLine($"G0 Z{N(p.SafeZ)}");
            }
            foreach (var m in p.Moves)
            {
                if (m.Kind == MoveKind.Rapid) sb.AppendLine($"G0 X{N(m.To.X)} Y{N(m.To.Y)} Z{N(m.To.Z)}");
                else
                {
                    var line = $"G1 X{N(m.To.X)} Y{N(m.To.Y)} Z{N(m.To.Z)}";
                    if (m.Extrude != 0) line += $" E{m.Extrude.ToString("0.#####", Inv)}";
                    if (Math.Abs(m.Feed - lastF) > 1e-9) { line += $" F{N(m.Feed)}"; lastF = m.Feed; }
                    sb.AppendLine(line);
                }
            }
            if (!additive) { sb.AppendLine($"G0 Z{N(p.SafeZ)}"); sb.AppendLine("M5"); }
        }
        if (additive) { sb.AppendLine("M104 S0"); sb.AppendLine("M140 S0"); sb.AppendLine("G91"); sb.AppendLine("G1 Z10 F600"); sb.AppendLine("G90"); sb.AppendLine("M84"); }
        else sb.AppendLine("G0 X0 Y0");
        sb.AppendLine(flavor == GCodeFlavor.Marlin ? "M84" : "M30");
        return sb.ToString();
    }
}
